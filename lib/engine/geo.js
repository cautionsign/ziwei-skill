// 默认坐标（北京，UTC+8）
const DEFAULT_COORDS = { lat: 39.9042, lng: 116.4074, tz: 8 };

/**
 * 查询城市坐标
 * @param {string} city - 城市名称
 * @returns {Object} { success, data: { latitude, longitude }, error }
 */
export function lookupCity(city) {
  if (!city || typeof city !== 'string') {
    return {
      success: false,
      error: '城市参数无效',
      data: null
    };
  }

  // 标准化输入
  const normalized = city.trim().replace(/市$/, '').replace(/省$/, '');

  // 检查别名
  const aliasKey = ALIASES[normalized];
  if (aliasKey) {
    const coords = CITY_DATA[aliasKey] || CITY_DATA[aliasKey + '市'];
    if (coords) {
      return {
        success: true,
        data: {
          latitude: coords.lat,
          longitude: coords.lng,
          timezone: coords.tz,
          city: aliasKey
        }
      };
    }
  }

  // 直接查找
  let coords = CITY_DATA[normalized] || CITY_DATA[normalized + '市'] || CITY_DATA[city];

  if (coords) {
    return {
      success: true,
      data: {
        latitude: coords.lat,
        longitude: coords.lng,
        timezone: coords.tz,
        city: normalized
      }
    };
  }

  // 模糊匹配：检查是否包含某个城市名
  for (const [name, coord] of Object.entries(CITY_DATA)) {
    if (city.includes(name.replace(/市$/, '')) || name.includes(normalized)) {
      return {
        success: true,
        data: {
          latitude: coord.lat,
          longitude: coord.lng,
          timezone: coord.tz,
          city: name
        }
      };
    }
  }

  // 未找到，返回默认坐标（北京）
  return {
    success: true,
    data: {
      latitude: DEFAULT_COORDS.lat,
      longitude: DEFAULT_COORDS.lng,
      timezone: DEFAULT_COORDS.tz,
      city: '北京（默认）'
    }
  };
}
